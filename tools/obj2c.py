"""Convert an OBJ (and optionally its texture) to a built-in engine mesh (C source). Game
content goes in places instead (see placec.py); this is for engine assets like the avatar.

    python3 tools/obj2c.py assets/model/guy.obj guy_mesh.c guy_mesh R,G,B [base.png tex_name [coat.png]]

With a coat layer, also emits `<tex_name>_coat_first`: the coat's greys are palette entries
from there to 15, so the coat can be tinted by swapping them (see avatar_texture()).

See objload.py for orientation, scaling and shading, and texload.py for textures. The mesh
is written unindexed (3 corners per triangle), as core's `mesh` struct expects.
"""
import sys

from objload import load_obj
from texload import load_texture

HEIGHT = 2.4

path, out, name, rgb = sys.argv[1], sys.argv[2], sys.argv[3], [int(c) for c in sys.argv[4].split(',')]
png, tex_name = (sys.argv[5], sys.argv[6]) if len(sys.argv) > 6 else (None, None)
coat = sys.argv[7] if len(sys.argv) > 7 else None
verts, uvs, tris, colors = load_obj(path, HEIGHT, rgb)
if png and uvs is None:
    sys.exit(f'{path}: has no texture coordinates (for the guy, run tools/guy_uvs.py first)')

sys.stdout = open(out, 'w', encoding='utf-8', newline='\n')
print(f'/* Generated by tools/obj2c.py from {path.replace(chr(92), "/")}; do not edit. */')
print('#include "world.h"\n')
if png:
    w, h, palette, pixels, su, sv, coat_first = load_texture(png, coat)
    uvs = [(round(u * su), round(v * sv)) for u, v in uvs]  # in case it was padded
    print(f'static const uint8_t tex_pixels[{len(pixels)}] = {{')
    for i in range(0, len(pixels), 16):
        print('    ' + ' '.join(f'0x{b:02x},' for b in pixels[i:i + 16]))
    print('};\n')
    print(f'texture {tex_name} = {{')
    print(f'    .w = {w},\n    .h = {h},\n    .pixels = tex_pixels,')
    print('    .palette = {' + ', '.join('{%d, %d, %d}' % c for c in palette) + '},')
    print('};\n')
    if coat:
        print(f'const int {tex_name}_coat_first = {coat_first};\n')
print(f'static const int16_t verts[{len(tris) * 3}][3] = {{')
for t in tris:
    print('    ' + ' '.join('{%d, %d, %d},' % verts[i] for i in t))
print('};\n')
if png:
    print(f'static const int16_t uvs[{len(tris) * 3}][2] = {{')
    for t in tris:
        print('    ' + ' '.join('{%d, %d},' % uvs[i] for i in t))
    print('};\n')
print(f'static const uint8_t colors[{len(tris)}][3] = {{')
for c in colors:
    print('    {%d, %d, %d},' % c)
print('};\n')
texture_fields = f', .uvs = uvs, .texture = &{tex_name}' if png else ''
print(f'const mesh {name} = {{.verts = verts, .colors = colors, .tris = {len(tris)}{texture_fields}}};')

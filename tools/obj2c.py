"""Convert an OBJ to a built-in engine mesh (C source). Game content goes in places instead
(see placec.py); this is for engine assets like the avatar.

    python3 tools/obj2c.py assets/model/guy.obj guy_mesh R,G,B > core/guy_mesh.c

See objload.py for orientation, scaling and shading. The mesh is written unindexed
(3 corners per triangle), as core's `mesh` struct expects.
"""
import sys

from objload import load_obj

HEIGHT = 2.4

path, name, rgb = sys.argv[1], sys.argv[2], [int(c) for c in sys.argv[3].split(',')]
verts, tris, colors = load_obj(path, HEIGHT, rgb)

print(f'/* Generated by tools/obj2c.py from {path.replace(chr(92), "/")}; do not edit. */')
print('#include "world.h"\n')
print(f'static const int16_t verts[{len(tris) * 3}][3] = {{')
for t in tris:
    print('    ' + ' '.join('{%d, %d, %d},' % verts[i] for i in t))
print('};\n')
print(f'static const uint8_t colors[{len(tris)}][3] = {{')
for c in colors:
    print('    {%d, %d, %d},' % c)
print('};\n')
print(f'const mesh {name} = {{verts, colors, {len(tris)}}};')
